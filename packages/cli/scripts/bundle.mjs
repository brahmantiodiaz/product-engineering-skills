import { build } from 'esbuild';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, sep } from 'node:path';
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const args = process.argv.slice(2);
if (args.length && (args[0] !== '--outfile' || args.length !== 2)) throw new Error('Usage: bundle.mjs [--outfile path]');
const outfile = args[1] ?? '../../skills/gyrospec/gyro/scripts/gyro.mjs';
const { metafile } = await build({
  entryPoints: ['src/bin.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node20',
  outfile, metafile: true,
  banner: { js: `#!/usr/bin/env node\n// Generated by packages/cli/scripts/bundle.mjs from @gyrospec/cli ${version}. Do not edit.` },
  define: { __GYRO_VERSION__: JSON.stringify(version) }, legalComments: 'none',
  // Dependency comments contain punctuation forbidden by this repository.
  minifyWhitespace: true,
});
// legalComments is off, so the licenses of the bundled third-party packages ship beside the bundle instead.
const packages = new Map();
const [output] = Object.values(metafile.outputs);
for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
  if (!bytesInOutput) continue;
  const parts = realpathSync(input).split(sep), at = parts.lastIndexOf('node_modules');
  if (at < 0) continue;
  const dir = parts.slice(0, at + (parts[at + 1].startsWith('@') ? 3 : 2)).join(sep);
  const { name, version: v, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  if (name.startsWith('@gyrospec/')) continue;
  const file = ['LICENSE', 'LICENSE.md', 'LICENSE.txt'].map(f => join(dir, f)).find(existsSync);
  if (!file) throw new Error(`${name} has no LICENSE file to ship`);
  packages.set(name, `## ${name} ${v} (${license})\n\n${readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()}\n`);
}
const header = `# Third-party licenses\n\nscripts/gyro.mjs bundles the packages below. Generated by packages/cli/scripts/bundle.mjs. Do not edit.\n`;
writeFileSync(join(dirname(outfile), 'THIRD_PARTY_LICENSES.txt'), [header, ...[...packages.keys()].sort().map(k => packages.get(k))].join('\n'));
